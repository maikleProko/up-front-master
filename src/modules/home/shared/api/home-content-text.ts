export const cleanHomeText = (value: string): string =>
	value
		.replace(/\s*\(демо\)/gi, "")
		.replace(/\s*[·—–-]\s*демо(?=\s*$)/gi, "")
		.replace(/\s*[—–-]\s*демонстрационный адрес/gi, "")
		.replace(/Пример графика:\s*/gi, "")
		.replace(/Демонстрационная публикация\.\s*|События вымышлены\.\s*/gi, "")
		.replace(/В этом примере новости рассказываем, как может выглядеть анонс новой поставки\.\s*/g, "")
		.replace(
			/Здесь можно разместить описание серии запчастей, особенности совместимости и рекомендации по подбору\.\s*/g,
			"",
		)
		.replace(/Это пример новости об открытии новой точки продаж\.\s*/g, "")
		.replace(/В настоящем анонсе здесь будут адрес, часы работы и информация об ассортименте\.\s*/g, "")
		.replace(/Две точки на карте главной страницы созданы для демонстрации интерфейса\.\s*/g, "")
		.replace(/Они не являются действующими магазинами\.\s*/g, "")
		.trim();
